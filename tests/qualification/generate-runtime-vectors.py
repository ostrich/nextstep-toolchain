#!/usr/bin/env python3
"""Generate deterministic arithmetic expectations using Python integers."""
from pathlib import Path
import random
r = random.Random(0x4e655854)
mask = (1 << 64) - 1
values = [1, 2, 3, 0x7fffffff, 0x80000000, 0xffffffff, 1 << 32,
          (1 << 63) - 1, 1 << 63, mask]
values += [r.getrandbits(64) or 1 for _ in range(54)]
def signed(n): return n - (1 << 64) if n >> 63 else n
rows = []
for i, a in enumerate(values):
    b = values[(i * 13 + 3) % len(values)]
    s, t = signed(a), signed(b)
    if s == -(1 << 63) and t == -1: b, t = 3, 3
    shift = i % 64
    q = abs(s) // abs(t)
    if (s < 0) != (t < 0): q = -q
    rem = s - q * t
    u = [a, b, a * b & mask, a // b, a % b, a << shift & mask, a >> shift,
         int.from_bytes(a.to_bytes(8, 'little'), 'big')]
    sfmt = lambda v: ('(-%dLL - 1LL)' % (-(v + 1))) if v < 0 else str(v) + 'LL'
    row = ', '.join('0x%xULL' % v for v in u)
    row += ', ' + ', '.join(sfmt(v) for v in [s >> shift, q, rem])
    row += ', ' + ', '.join(str(v) for v in [shift, a.bit_count(), 64 - a.bit_length(), (a & -a).bit_length() - 1])
    rows.append('  { ' + row + ' }')
text = '''/* Generated by tests/qualification/generate-runtime-vectors.py. */
static const struct {
  U a, b, mul, div, rem, left, right, swapped;
  S signed_right, signed_div, signed_rem;
  unsigned shift, popcount, clz, ctz;
} vectors[] = {
''' + ',\n'.join(rows) + '\n};\n'
(Path(__file__).resolve().parents[2] / 'tests/runtime-vectors.h').write_text(text)
