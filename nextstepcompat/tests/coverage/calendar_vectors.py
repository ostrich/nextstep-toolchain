"""Independent Gregorian/ISO-week expectations, without host strftime."""
import calendar
import datetime
import json


def generate(path):
    rows = []
    for year in range(1996, 2396):
        dates = [(1, 1), (1, 4), (2, 28), (3, 1), (12, 28), (12, 31)]
        if calendar.isleap(year):
            dates.append((2, 29))
        for month, day in dates:
            date = datetime.date(year, month, day)
            yday = (date - datetime.date(year, 1, 1)).days
            wday = (date.weekday() + 1) % 7
            sunday = (yday + 7 - wday) // 7
            monday = (yday + 7 - date.weekday()) // 7
            iso_year, iso_week, iso_day = date.isocalendar()
            c90 = f'{year:04} {month:02} {day:02} {yday+1:03} {wday} {sunday:02} {monday:02}'
            c99 = f'{year:04}-{month:02}-{day:02} {year//100:02} {iso_day} {iso_week:02} {iso_year:04} {iso_year%100:02}'
            rows.append(f'  {{{year-1900},{month-1},{day},{yday},{wday},{json.dumps(c90)},{json.dumps(c99)}}},\n')
    path.write_text('/* Generated by calendar_vectors.py from integer calendar arithmetic. */\n'
                    'static const struct vector vectors[] = {\n' + ''.join(rows) + '};\n')
