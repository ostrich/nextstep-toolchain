#!/usr/bin/env python3
"""Build binary64/realtime tests and verify their high-precision reference table."""
import argparse
from decimal import Decimal, localcontext
import hashlib
import json
import math
from pathlib import Path
import random
import subprocess
ROOT = Path(__file__).resolve().parents[1]


def vectors():
    values = set()
    for exponent in range(-52, 0):
        values.add(1.0 + 2.0 ** exponent)
        values.add(1.0 - 2.0 ** exponent)
    random_source = random.Random(53133)
    for _ in range(160):
        values.add(math.ldexp(1 + random_source.random(), random_source.randrange(-1022, 1023)))
    result = ('/* Binary64 nearest-rounding references generated by Decimal at 160 digits.\n'
              '   See build-math-clock.py for the reproducible generator. */\n'
              'static const struct { double x, expected; } log2_vectors[] = {\n')
    with localcontext() as context:
        context.prec = 160
        ln2 = Decimal(2).ln()
        for x in sorted(values):
            result += '  { ' + x.hex() + ', ' + float(Decimal(x).ln() / ln2).hex() + ' },\n'
    return result + '};\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for name in ['toolchain', 'sdk', 'compat', 'output']:
        p.add_argument('--' + name, type=Path, required=True)
    p.add_argument('--shared', action='store_true')
    a = p.parse_args()
    if vectors() != (ROOT / 'tests/math-log2-vectors.h').read_text():
        p.error('High-precision reference table differs from its generator')
    tc, sdk, compat, out = [x.resolve() for x in [a.toolchain, a.sdk, a.compat, a.output]]
    if out.exists():
        p.error('Use a fresh output directory')
    out.mkdir(parents=True)
    record = {'steps': [], 'toolchain_manifest_sha256': hashlib.sha256((tc / 'toolchain.json').read_bytes()).hexdigest(),
              'tests_sha256': {name: hashlib.sha256((ROOT / 'tests' / name).read_bytes()).hexdigest()
                               for name in ['math-clock.c', 'math-log2-vectors.h']}}
    for arch in ['m68k', 'i386', 'hppa', 'sparc']:
        library = compat / 'libnextstepcompat.a' if a.shared else compat / arch / 'libnextstepcompat.a'
        cmd = [str(tc / 'bin/nextstep-gcc'), '--sdk', str(sdk), '--compat-headers', str(ROOT / 'include'),
               '-arch', arch, '-O2', '-fno-builtin', str(ROOT / 'tests/math-clock.c'),
               str(library), '-o', str(out / ('math-clock-' + arch))]
        subprocess.run(cmd, check=True)
        record['steps'].append(cmd)
    subprocess.run([str(tc / 'libexec/cctools/lipo'), '-create',
                    *[str(out / ('math-clock-' + arch)) for arch in ['m68k', 'i386', 'hppa', 'sparc']],
                    '-output', str(out / 'math-clock')], check=True)
    record['binary_sha256'] = hashlib.sha256((out / 'math-clock').read_bytes()).hexdigest()
    (out / 'build-record.json').write_text(json.dumps(record, indent=2) + '\n')


if __name__ == '__main__':
    main()
